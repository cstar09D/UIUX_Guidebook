import type {
  DetailedGuide,
  GuidePoint,
  RoleName,
  ScreenExample,
} from "./guide-content";
import type { DemoId } from "./catalog";
type Pair = [string, string];
type Draft = {
  title: string;
  intro: string;
  uses: Pair[];
  flow: Pair[];
  examples: ScreenExample[];
  pitfalls: Pair[];
  alternatives: [DemoId, string, string][];
  practice: string;
  contract: string;
  roles: Record<RoleName, [string, string, string]>;
  checks: [string, string];
};
const point = ([title, body]: Pair): GuidePoint => ({ title, body });
const screen = (
  id: string,
  label: string,
  title: string,
  condition: string,
  explanation: string,
  body: string,
  items?: string[],
  action?: string,
  tone?: "error" | "success" | "loading",
): ScreenExample => ({
  id,
  label,
  title,
  condition,
  explanation,
  screen: {
    title,
    body,
    ...(items ? { items } : {}),
    ...(action ? { action } : {}),
    ...(tone ? { tone } : {}),
  },
});
function define(d: Draft): DetailedGuide {
  const role = (name: RoleName): DetailedGuide["roles"][RoleName] => ({
    goal: `${d.title}의 ${name} 관점에서 상태·조작·결과를 일치시킵니다.`,
    tasks: d.roles[name].map((body, i) => ({
      title: ["사용 조건과 구조", "상태·예외 처리", "협업과 완료 기준"][i],
      body,
    })),
    handoff: `${name} 전달 예시: ${d.contract}`,
    checks: d.checks,
  });
  return {
    introduction: d.intro,
    uses: d.uses.map(point),
    flow: d.flow.map(point),
    examples: d.examples,
    pitfalls: d.pitfalls.map(point),
    alternatives: d.alternatives.map(([targetDemoId, title, body]) => ({
      targetDemoId,
      title,
      body,
    })),
    practice: d.practice,
    roles: {
      기획: role("기획"),
      디자인: role("디자인"),
      프론트엔드: role("프론트엔드"),
      개발: role("개발"),
    },
  };
}
