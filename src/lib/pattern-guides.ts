import type {
  DetailedGuide,
  GuidePoint,
  RoleName,
  ScreenExample,
} from "./guide-content";
type Pair = readonly [string, string];
type Draft = {
  title: string;
  intro: string;
  uses: Pair[];
  flow: Pair[];
  examples: ScreenExample[];
  pitfalls: Pair[];
  alternatives: Pair[];
  practice: string;
  contract: string;
  tasks: Record<RoleName, string[]>;
  checks: Record<RoleName, string[]>;
};
const point = ([title, body]: Pair): GuidePoint => ({ title, body });
const example = (
  id: string,
  label: string,
  title: string,
  condition: string,
  explanation: string,
  screen: ScreenExample["screen"],
): ScreenExample => ({ id, label, title, condition, explanation, screen });
function guide(d: Draft): DetailedGuide {
  const goals = {
    기획: "진입 조건·확정·취소와 예외 정책을 구체화합니다.",
    디자인: "기본·오류·완료와 화면 크기별 표현을 연결합니다.",
    프론트엔드: "입력 의미·키보드·초점·상태 전환을 구현합니다.",
    개발: "데이터 계약과 실제 처리 결과의 일관성을 보장합니다.",
  };
  const titles = {
    기획: ["조건과 범위", "예외와 취소", "확정과 후속 행동"],
    디자인: ["기본 정보와 행동", "상태별 표현", "작은 화면과 대안"],
    프론트엔드: ["구조와 키보드", "상태와 입력값", "검증과 초점"],
    개발: ["데이터 계약", "실패와 취소", "완료와 일관성"],
  };
  return {
    introduction: d.intro,
    uses: d.uses.map(point),
    flow: d.flow.map(point),
    examples: d.examples,
    pitfalls: d.pitfalls.map(point),
    alternatives: d.alternatives.map(point),
    practice: d.practice,
    roles: Object.fromEntries(
      (Object.keys(goals) as RoleName[]).map((role) => [
        role,
        {
          goal: `${d.title}: ${goals[role]}`,
          tasks: d.tasks[role].map((body, index) => ({
            title: titles[role][index],
            body,
          })),
          handoff: `${role} 전달 예: ${d.contract} 정상·오류·취소 화면과 결과를 함께 검토합니다.`,
          checks: d.checks[role],
        },
      ]),
    ) as DetailedGuide["roles"],
  };
}
